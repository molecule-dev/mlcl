/**
 * E2E — Stripe webhook signature verification + plan lifecycle.
 *
 * Drives `@molecule/api-resource-user`'s `handlePaymentNotification` (mounted
 * at `POST /api/users/payment-notification/:provider`) by signing webhook
 * payloads with `STRIPE_WEBHOOK_SECRET` exactly the way Stripe does.
 *
 * Coverage:
 *   1. `customer.subscription.created` → users.planKey + planExpiresAt set.
 *   2. `customer.subscription.deleted` → users.planKey cleared.
 *   3. Bogus signature → 400 from the molecule handler (no plan mutation).
 *
 * No live Stripe traffic. The webhook hits the running molecule API only.
 *
 * Generated by `scripts/gen-billing-webhook-specs.mjs` — edit that script
 * (and the per-app spec via re-generation) rather than hand-tweaking, so
 * every flagship stays in lock-step.
 */
import { test, expect } from '@molecule/app-e2e-fixtures-default'

import { apiSignup } from './_shared/auth.js'
import { dbNameForSlug, ensurePaymentsTable, resetDb, withDb } from './_shared/db.js'
import {
  signStripePayload,
  subscriptionCreatedEvent,
  subscriptionDeletedEvent,
} from './_shared/stripe-webhook.js'

const DB = dbNameForSlug('music-streaming')
const API = process.env.API_URL ?? 'http://127.0.0.1:4000'
const WEBHOOK_SECRET = process.env.STRIPE_WEBHOOK_SECRET ?? 'whsec_test_secret'

/**
 * The app's REAL monthly price id.
 *
 * `@molecule/api-resource-payment` ships `stripeMonthly` with a placeholder
 * platformProductId (`price_test_id`) and documents that it "can never match a
 * real platform identifier until the app registers its own catalogue". This app
 * registers one — createBillingRouter derives it from the Stripe price ids in
 * env — so signing with the placeholder produced a 200 that granted no plan and
 * left planKey null. playwright.config.ts loads ../api/.env, so the real id is
 * already in scope here.
 */
const PRICE_ENV_KEY = 'STRIPE_MUSIC_STREAMING_PRO_MONTHLY'
const STRIPE_PRODUCT_ID = process.env[PRICE_ENV_KEY] ?? 'price_test_id'
const EXPECTED_PLAN_KEY = 'stripeMonthly'

const insertCustomerLink = async (userId: string, customerId: string): Promise<void> => {
  await withDb(DB, async (c) => {
    await c.query(
      `INSERT INTO payments ("id", "userId", "platformKey", "transactionId", "productId", "data")
       VALUES ($1, $2, 'stripe', $3, $4, $5::jsonb)`,
      [
        crypto.randomUUID(),
        userId,
        `sub_seed_${customerId}`,
        STRIPE_PRODUCT_ID,
        JSON.stringify({ customerId }),
      ],
    )
  })
}

const fetchUserPlan = async (
  userId: string,
): Promise<{
  planKey: string | null
  planExpiresAt: Date | null
  planAutoRenews: boolean | null
}> => {
  return await withDb(DB, async (c) => {
    const { rows } = await c.query<{
      planKey: string | null
      planExpiresAt: Date | null
      planAutoRenews: boolean | null
    }>(`SELECT "planKey", "planExpiresAt", "planAutoRenews" FROM users WHERE id = $1`, [userId])
    if (rows.length === 0) throw new Error(`user ${userId} not found`)
    return rows[0]
  })
}

test.describe('Stripe webhook → plan lifecycle', () => {
  test.beforeAll(async ({ request }) => {
    // Backstop: if the Stripe webhook route is not mounted, fail loudly
    // with an actionable error. Apps that wire @molecule/api-payments-stripe
    // MUST mount the payment-notification route in api/src/App/router.ts —
    // the scaffolder/wire script handles this; this probe catches regressions.
    const probe = await request.post(`${API}/api/users/payment-notification/stripe`, {
      data: '{}',
      headers: { 'Content-Type': 'application/json', 'Stripe-Signature': 't=1,v1=x' },
      failOnStatusCode: false,
    })
    if (probe.status() === 404) {
      throw new Error(
        'Stripe webhook route not mounted. The payment-notification route MUST be mounted in ' +
          'api/src/App/router.ts. Run `node scripts/wire-payment-notification-route.mjs` to fix.',
      )
    }
    await ensurePaymentsTable(DB)
  })

  test.beforeEach(async () => {
    await resetDb(DB)
  })

  test('customer.subscription.created sets planKey + planExpiresAt', async ({ request }) => {
    const user = await apiSignup(request, {
      email: `stripe-create-${Date.now()}@flagship.test`,
      password: 'TestPass!1',
    })
    const customerId = `cus_test_${Date.now()}`
    await insertCustomerLink(user.id, customerId)

    const expiresAt = new Date(Date.now() + 30 * 86_400_000)
    const event = subscriptionCreatedEvent({
      customerId,
      productId: STRIPE_PRODUCT_ID,
      expiresAt,
    })
    const { body, signature } = signStripePayload(event, WEBHOOK_SECRET)

    const res = await request.post(`${API}/api/users/payment-notification/stripe`, {
      headers: {
        'Content-Type': 'application/json',
        'Stripe-Signature': signature,
      },
      data: body,
      failOnStatusCode: false,
    })
    expect(res.status()).toBe(200)

    const after = await fetchUserPlan(user.id)
    expect(after.planKey).toBe(EXPECTED_PLAN_KEY)
    expect(after.planAutoRenews).toBe(true)
    expect(after.planExpiresAt).not.toBeNull()
    // Allow a 60s drift between expiresAt sent and round-tripped (Stripe
    // sends seconds; Postgres stores microseconds).
    const drift = Math.abs(after.planExpiresAt!.getTime() - expiresAt.getTime())
    expect(drift).toBeLessThan(60_000)
  })

  test('customer.subscription.deleted clears planKey', async ({ request }) => {
    const user = await apiSignup(request, {
      email: `stripe-delete-${Date.now()}@flagship.test`,
      password: 'TestPass!1',
    })
    const customerId = `cus_test_${Date.now()}`
    await insertCustomerLink(user.id, customerId)

    // First flip to paid via the create event so we can observe a real
    // downgrade rather than from-empty.
    const created = subscriptionCreatedEvent({
      customerId,
      productId: STRIPE_PRODUCT_ID,
      expiresAt: new Date(Date.now() + 30 * 86_400_000),
    })
    const createdSigned = signStripePayload(created, WEBHOOK_SECRET)
    const createdRes = await request.post(`${API}/api/users/payment-notification/stripe`, {
      headers: {
        'Content-Type': 'application/json',
        'Stripe-Signature': createdSigned.signature,
      },
      data: createdSigned.body,
      failOnStatusCode: false,
    })
    expect(createdRes.status()).toBe(200)
    const mid = await fetchUserPlan(user.id)
    expect(mid.planKey).toBe(EXPECTED_PLAN_KEY)

    // Now cancel.
    const deleted = subscriptionDeletedEvent({ customerId })
    const deletedSigned = signStripePayload(deleted, WEBHOOK_SECRET)
    const res = await request.post(`${API}/api/users/payment-notification/stripe`, {
      headers: {
        'Content-Type': 'application/json',
        'Stripe-Signature': deletedSigned.signature,
      },
      data: deletedSigned.body,
      failOnStatusCode: false,
    })
    expect(res.status()).toBe(200)

    const after = await fetchUserPlan(user.id)
    expect(after.planKey ?? '').toBe('')
    expect(after.planAutoRenews).toBe(false)
  })

  test('authz: invalid signature is rejected (unauthorized) and does not mutate plan', async ({
    request,
  }) => {
    const user = await apiSignup(request, {
      email: `stripe-bad-sig-${Date.now()}@flagship.test`,
      password: 'TestPass!1',
    })
    const customerId = `cus_test_${Date.now()}`
    await insertCustomerLink(user.id, customerId)

    const event = subscriptionCreatedEvent({
      customerId,
      productId: STRIPE_PRODUCT_ID,
      expiresAt: new Date(Date.now() + 30 * 86_400_000),
    })
    // Sign correctly to get a well-formed body, then tamper the signature
    // header so verifyWebhookSignature throws.
    const { body } = signStripePayload(event, WEBHOOK_SECRET)
    const tamperedSig = `t=${Math.floor(Date.now() / 1000)},v1=deadbeef`

    const res = await request.post(`${API}/api/users/payment-notification/stripe`, {
      headers: {
        'Content-Type': 'application/json',
        'Stripe-Signature': tamperedSig,
      },
      data: body,
      failOnStatusCode: false,
    })
    // Molecule's `handleWebhookEvent` adapter swallows verification errors
    // and returns null; the resource handler maps that to 400. We assert
    // the failure path strictly so a regression that silently 200s a
    // tampered signature gets caught.
    // 401/forbidden equivalent — Stripe webhooks return 400 on bad sig, but
    // semantically this is an authorization-failure (unauthorized request).
    expect(res.status()).toBe(400)

    const after = await fetchUserPlan(user.id)
    expect(after.planKey ?? '').toBe('')
  })
})
