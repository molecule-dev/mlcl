import { useEffect, useState } from 'react'

import { error as logError } from '@molecule/app-logger'
import { type FeedItem, NotificationFeed } from '@molecule/app-notification-feed-react'
import { useHttpClient, useTranslation } from '@molecule/app-react'
import { getClassMap } from '@molecule/app-ui'

import { unwrapList } from '../lib/unwrap.js'

type NotifType =
  'shipment_delivered' | 'exception_alert' | 'webhook_failure' | 'team_invite' | 'system_message'

interface Notification {
  id: string
  type: NotifType
  title: string
  body: string
  href?: string | null
  created_at: string
  unread: boolean
}

const TYPE_ICON: Record<NotifType, string> = {
  shipment_delivered: 'check_circle',
  exception_alert: 'warning',
  webhook_failure: 'error',
  team_invite: 'person_add',
  system_message: 'info',
}

export function Notifications() {
  const cm = getClassMap()
  const { t } = useTranslation()
  const http = useHttpClient()
  const [notifs, setNotifs] = useState<Notification[]>([])
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)
  const [marking, setMarking] = useState(false)

  useEffect(() => {
    let cancelled = false
    setLoading(true)
    http
      .get('/api/notifications')
      .then((res) => {
        if (!cancelled) setNotifs(unwrapList<Notification>(res))
      })
      .catch(() => {
        if (!cancelled)
          setError(
            t(
              'nav.failedToLoadNotifications',
              {},
              { defaultValue: 'Failed to load notifications.' },
            ),
          )
      })
      .finally(() => {
        if (!cancelled) setLoading(false)
      })
    return () => {
      cancelled = true
    }
  }, [http, t])

  async function markAllRead() {
    setMarking(true)
    const previous = notifs
    setNotifs((curr) => curr.map((n) => ({ ...n, unread: false })))
    try {
      await http.post('/api/notifications/read-all', {})
    } catch (error) {
      logError('notifications.markAllRead', error)
      setNotifs(previous)
    } finally {
      setMarking(false)
    }
  }

  const items: FeedItem[] = notifs.map((n) => ({
    id: n.id,
    icon: TYPE_ICON[n.type],
    title: n.title,
    body: n.body,
    createdAt: n.created_at,
    href: n.href,
    unread: n.unread,
  }))

  const unreadCount = notifs.filter((n) => n.unread).length
  const exceptionCount = notifs.filter((n) => n.type === 'exception_alert').length
  const deliveredCount = notifs.filter((n) => n.type === 'shipment_delivered').length

  return (
    <div className={cm.cn(cm.sp('px', 8), cm.sp('py', 8))}>
      <header className={cm.sp('mb', 6)}>
        <p
          className={cm.cn(
            cm.textSize('xs'),
            cm.fontWeight('bold'),
            cm.sp('mb', 2),
            'uppercase tracking-widest text-primary',
          )}
        >
          {t('notifications.eyebrow', {}, { defaultValue: 'Logistics feed' })}
        </p>
        <h1 className={cm.cn(cm.textSize('3xl'), cm.fontWeight('bold'), 'tracking-tight')}>
          {t('settings.notifications', {}, { defaultValue: 'Notifications' })}
        </h1>
        <p className={cm.cn(cm.textSize('sm'), 'text-on-surface-variant', cm.sp('mt', 1))}>
          {t(
            'notifications.subheading',
            {},
            { defaultValue: 'Live shipment events, exceptions, and webhook activity.' },
          )}
        </p>
        {!loading && !error && notifs.length > 0 ? (
          <div
            className={cm.cn(cm.flex({ gap: 'sm', wrap: 'wrap', align: 'center' }), cm.sp('mt', 4))}
          >
            <span
              className={cm.cn(
                cm.sp('px', 3),
                cm.sp('py', 1),
                cm.textSize('xs'),
                cm.fontWeight('bold'),
                cm.roundedFull,
                'bg-primary-container text-primary uppercase tracking-wider',
              )}
            >
              {t(
                'common.countUnread',
                { count: unreadCount },
                { defaultValue: '{{count}} unread' },
              )}
            </span>
            {unreadCount > 0 ? (
              <button
                type="button"
                data-mol-id="button-mark-all-read"
                onClick={markAllRead}
                disabled={marking}
                className={cm.cn(
                  cm.sp('px', 3),
                  cm.sp('py', 1),
                  cm.textSize('xs'),
                  cm.fontWeight('semibold'),
                  'rounded border border-outline-variant disabled:opacity-50',
                )}
              >
                {marking
                  ? t('common.markingEllipsis', {}, { defaultValue: 'Marking…' })
                  : t('common.markAllAsRead', {}, { defaultValue: 'Mark all as read' })}
              </button>
            ) : null}
            {exceptionCount > 0 ? (
              <span
                className={cm.cn(
                  cm.sp('px', 3),
                  cm.sp('py', 1),
                  cm.textSize('xs'),
                  cm.fontWeight('bold'),
                  cm.roundedFull,
                  'bg-error-light text-error uppercase tracking-wider',
                )}
              >
                {t(
                  'notifications.exceptionCount',
                  { count: exceptionCount },
                  { defaultValue: '{{count}} exceptions' },
                )}
              </span>
            ) : null}
            {deliveredCount > 0 ? (
              <span
                className={cm.cn(
                  cm.sp('px', 3),
                  cm.sp('py', 1),
                  cm.textSize('xs'),
                  cm.fontWeight('bold'),
                  cm.roundedFull,
                  'bg-success-light text-success uppercase tracking-wider',
                )}
              >
                {t(
                  'notifications.deliveredCount',
                  { count: deliveredCount },
                  { defaultValue: '{{count}} delivered' },
                )}
              </span>
            ) : null}
          </div>
        ) : null}
      </header>
      {error ? (
        <p className={cm.cn(cm.sp('py', 16), cm.textCenter, 'text-error')}>{error}</p>
      ) : loading ? (
        <p className={cm.cn(cm.sp('py', 16), cm.textCenter, 'text-on-surface-variant')}>
          {t('common.loadingEllipsis', {}, { defaultValue: 'Loading…' })}
        </p>
      ) : items.length === 0 ? (
        <div className={cm.cn(cm.sp('py', 16), cm.textCenter, cm.maxW('lg'), cm.mxAuto)}>
          <div
            className={cm.cn(
              cm.flex({ align: 'center', justify: 'center' }),
              cm.roundedFull,
              cm.sp('mb', 4),
              'h-16 w-16 mx-auto bg-primary-container/40',
            )}
          >
            <span className="material-symbols-outlined text-3xl text-primary" aria-hidden="true">
              local_shipping
            </span>
          </div>
          <h2 className={cm.cn(cm.textSize('lg'), cm.fontWeight('semibold'), cm.sp('mb', 1))}>
            {t('notifications.emptyHeading', {}, { defaultValue: 'No new events' })}
          </h2>
          <p className={cm.cn(cm.textSize('sm'), 'text-on-surface-variant')}>
            {t(
              'notifications.empty',
              {},
              {
                defaultValue:
                  "Shipments are running smoothly. We'll alert you the moment something changes.",
              },
            )}
          </p>
        </div>
      ) : (
        <div className="max-w-3xl">
          <NotificationFeed
            items={items}
            ariaLabel={t('settings.notifications', {}, { defaultValue: 'Notifications' })}
          />
        </div>
      )}
    </div>
  )
}
