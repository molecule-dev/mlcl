import { existsSync, readFileSync } from 'node:fs'
import { readdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

import { formatGeneratedSource, sortImportStatements } from './format.js'
import { SUPPORTED_LOCALES } from './locales.js'
import { getSharedCodeDir, requirePackageByRole } from './registry.js'

type AppLocaleManifest = {
  molecule?: { framework?: string; locales?: string[] }
}

const LEGAL_MODULES = ['privacyPolicy', 'termsOfService'] as const

/** The locales a custom scaffold can materialize, in the order requested by its creator. */
export function parseAppLocales(value: string, templatesDir: string): string[] {
  const available = SUPPORTED_LOCALES.map(({ code }) => code).filter((code) =>
    existsSync(join(templatesDir, 'app', 'shared', 'locales', code, 'ui.ts.tpl')),
  )
  const locales = [...new Set(value.split(',').map((code) => code.trim()))]
  for (const code of locales) {
    if (!available.includes(code)) {
      throw new Error(`Unknown app locale "${code}". Available locales: ${available.join(', ')}`)
    }
  }
  return locales
}

/** Read the custom scaffold's locale selection. Older apps and flagships have no selection. */
export function projectAppLocales(appDir: string): string[] | undefined {
  const manifest = join(appDir, 'package.json')
  if (!existsSync(manifest)) return undefined
  const { molecule } = JSON.parse(readFileSync(manifest, 'utf-8')) as AppLocaleManifest
  const locales = molecule?.locales
  if (locales === undefined) return undefined
  if (
    !Array.isArray(locales) ||
    locales.length === 0 ||
    locales.some((code) => !SUPPORTED_LOCALES.some((locale) => locale.code === code))
  ) {
    throw new Error(`Invalid molecule.locales selection in ${manifest}.`)
  }
  return locales
}

/** Directory where this app framework stores its own translations. */
export function appLocaleDirectory(appDir: string): string {
  const { molecule } = JSON.parse(
    readFileSync(join(appDir, 'package.json'), 'utf-8'),
  ) as AppLocaleManifest
  return join(appDir, 'src', getSharedCodeDir(molecule?.framework ?? '') ?? '', 'locales')
}

/** Render literal imports, understood by both Vite and Metro, from the same ordered selection. */
export async function writeAppLocaleLoaders(
  dir: string,
  locales: readonly string[],
): Promise<void> {
  const [primary, ...secondary] = locales
  const definitions = locales.map((code) =>
    SUPPORTED_LOCALES.find((locale) => locale.code === code),
  )
  const legal = locales.map((code) => {
    const loaders = LEGAL_MODULES.filter((name) => existsSync(join(dir, code, `${name}.ts`))).map(
      (name) => `    ${name}: async () => (await import('./${code}/${name}.js')).${name},`,
    )
    return `  ${JSON.stringify(code)}: {\n${loaders.join('\n')}\n  },`
  })
  const file = join(dir, 'project.ts')
  const contents = `// Generated by mlcl. Edit the dictionaries in each locale folder.
import { ui as primaryUi } from './${primary}/ui.js'

export { primaryUi }
export const primaryLocale = '${primary}'
export const localeDefinitions = ${JSON.stringify(definitions)} as const
export const supportedLocales = localeDefinitions.map(({ code }) => code)

const load: Partial<Record<string, () => Promise<{ ui: Record<string, string> }>>> = {
  ${secondary.map((code) => `${JSON.stringify(code)}: () => import('./${code}/ui.js'),`).join('\n  ')}
}

export async function lazyLoadUi(code: string): Promise<Record<string, string>> {
  if (code === primaryLocale) return primaryUi
  return (await load[code]?.())?.ui ?? {}
}

type ContentLoader = () => Promise<Record<string, string>>
const legal: Partial<Record<string, Partial<Record<string, ContentLoader>>>> = {
${legal.join('\n')}
}

export async function loadLocaleContent(code: string, module: string): Promise<Record<string, string>> {
  return (await legal[code]?.[module]?.()) ?? {}
}
`
  await writeFile(file, await formatGeneratedSource(contents, file))
}

type LoadDictionary = (locale: string) => Promise<Record<string, string> | undefined>

/** Read the exact dictionaries the installed runtime loaders serve for these locales. */
export async function appBondLocaleKeys(
  locales: readonly string[],
  bonds: readonly string[],
  resolvePackage: (name: string) => Promise<string | null>,
): Promise<ReadonlyMap<string, ReadonlySet<string>>> {
  const dictionaries = await Promise.all(
    bonds.map(async (name) => {
      const root = await resolvePackage(name)
      if (!root) throw new Error(`Install ${name} before generating the app translation types.`)
      const manifest = JSON.parse(readFileSync(join(root, 'package.json'), 'utf-8')) as {
        exports?: { './loader.js'?: { import?: string } }
      }
      const entry = manifest.exports?.['./loader.js']?.import
      if (!entry) throw new Error(`${name} does not export its locale loader.`)
      // A source checkout found through the registry path has no build output until it is built.
      if (!existsSync(join(root, entry)))
        throw new Error(
          `${name} at ${root} has no ${entry.replace(/^\.\//, '')}: install the package (npm install) or build that copy, then run this again.`,
        )
      const { loadLocaleModule } = (await import(pathToFileURL(join(root, entry)).href)) as {
        loadLocaleModule: LoadDictionary
      }
      return loadLocaleModule
    }),
  )
  return new Map(
    await Promise.all(
      locales.map(async (locale) => {
        const keys = new Set<string>()
        for (const catalog of await Promise.all(dictionaries.map((load) => load(locale)))) {
          for (const [key, value] of Object.entries(catalog ?? {})) {
            if (typeof value === 'string') keys.add(key)
          }
        }
        return [locale, keys] as const
      }),
    ),
  )
}

/** The compiler checks call sites as part of the app's existing build and editor typechecks. */
export async function writeAppLocaleTypes(
  dir: string,
  locales: readonly string[],
  bondKeys: ReadonlyMap<string, ReadonlySet<string>> = new Map(),
): Promise<void> {
  const i18n = requirePackageByRole('app', 'core', 'i18n')
  const primaryKeys = [...(bondKeys.get(locales[0]) ?? [])]
  const shared = new Set(
    primaryKeys.filter((key) => locales.every((l) => bondKeys.get(l)?.has(key))),
  )
  const catalogs = await Promise.all(
    locales.map(async (code) => {
      const modules = await readdir(join(dir, code))
      const app = ['ui', ...LEGAL_MODULES]
        .filter((name) => modules.includes(`${name}.ts`))
        .map((name) => ({ name, alias: `${code.replace('-', '')}_${name}` }))
      const extra = [...(bondKeys.get(code) ?? [])].filter((key) => !shared.has(key)).sort()
      return {
        imports: app.map(
          ({ name, alias }) => `import type { ${name} as ${alias} } from './${code}/${name}.js'`,
        ),
        member: `    ${JSON.stringify(code)}: ${[
          'SharedBondKeys',
          ...app.map(({ alias }) => `CatalogKeys<typeof ${alias}>`),
          ...extra.map((key) => JSON.stringify(key)),
        ].join(' | ')}`,
      }
    }),
  )
  const file = join(dir, 'catalogs.d.ts')
  const contents = `// Generated from the app catalogs and installed locale bonds by mlcl.
import '${i18n}'
${catalogs.flatMap(({ imports }) => imports).join('\n')}

type CatalogKeys<T> = string extends keyof T ? never : Extract<keyof T, string>
type SharedBondKeys = ${
    [...shared]
      .sort()
      .map((key) => JSON.stringify(key))
      .join(' | ') || 'never'
  }

declare module '${i18n}' {
  interface TranslationCatalogs {
${catalogs.map(({ member }) => member).join('\n')}
  }
}
`
  const next = await formatGeneratedSource(sortImportStatements(contents, file), file)
  if (!existsSync(file) || readFileSync(file, 'utf-8') !== next) await writeFile(file, next)
}
