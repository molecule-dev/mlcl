import { existsSync, readFileSync } from 'node:fs'
import { readdir, rm, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

import { CLI_COMMAND } from '#cli-command'

import { installedPackageDir } from './add-guidance.js'
import { formatGeneratedSource, sortImportStatements } from './format.js'
import { SUPPORTED_LOCALES } from './locales.js'
import { getSharedCodeDir, requirePackageByRole } from './registry.js'

type AppLocaleManifest = {
  molecule?: { framework?: string; locales?: string[] }
}

const LEGAL_MODULES = ['privacyPolicy', 'termsOfService'] as const

/** The locales a custom scaffold can materialize, in the order requested by its creator. */
export function parseAppLocales(value: string, templatesDir: string): string[] {
  const available = SUPPORTED_LOCALES.map(({ code }) => code).filter((code) =>
    existsSync(join(templatesDir, 'app', 'shared', 'locales', code, 'ui.ts.tpl')),
  )
  const locales = [...new Set(value.split(',').map((code) => code.trim()))]
  for (const code of locales) {
    if (!available.includes(code)) {
      throw new Error(`Unknown app locale "${code}". Available locales: ${available.join(', ')}`)
    }
  }
  return locales
}

/** Read the custom scaffold's locale selection. Older apps and flagships have no selection. */
export function projectAppLocales(appDir: string): string[] | undefined {
  const manifest = join(appDir, 'package.json')
  if (!existsSync(manifest)) return undefined
  const { molecule } = JSON.parse(readFileSync(manifest, 'utf-8')) as AppLocaleManifest
  const locales = molecule?.locales
  if (locales === undefined) return undefined
  if (
    !Array.isArray(locales) ||
    locales.length === 0 ||
    locales.some((code) => !SUPPORTED_LOCALES.some((locale) => locale.code === code))
  ) {
    throw new Error(`Invalid molecule.locales selection in ${manifest}.`)
  }
  return locales
}

/** Directory where this app framework stores its own translations. */
export function appLocaleDirectory(appDir: string): string {
  const { molecule } = JSON.parse(
    readFileSync(join(appDir, 'package.json'), 'utf-8'),
  ) as AppLocaleManifest
  return join(appDir, 'src', getSharedCodeDir(molecule?.framework ?? '') ?? '', 'locales')
}

/** Render literal imports, understood by both Vite and Metro, from the same ordered selection. */
export async function writeAppLocaleLoaders(
  dir: string,
  locales: readonly string[],
): Promise<void> {
  const [primary, ...secondary] = locales
  const definitions = locales.map((code) =>
    SUPPORTED_LOCALES.find((locale) => locale.code === code),
  )
  const legal = locales.map((code) => {
    const loaders = LEGAL_MODULES.filter((name) => existsSync(join(dir, code, `${name}.ts`))).map(
      (name) => `    ${name}: async () => (await import('./${code}/${name}.js')).${name},`,
    )
    return `  ${JSON.stringify(code)}: {\n${loaders.join('\n')}\n  },`
  })
  const file = join(dir, 'project.ts')
  const contents = `// Generated by mlcl. Edit the dictionaries in each locale folder.
import { ui as primaryUi } from './${primary}/ui.js'

export { primaryUi }
export const primaryLocale = '${primary}'
export const localeDefinitions = ${JSON.stringify(definitions)} as const
export const supportedLocales = localeDefinitions.map(({ code }) => code)

const load: Partial<Record<string, () => Promise<{ ui: Record<string, string> }>>> = {
  ${secondary.map((code) => `${JSON.stringify(code)}: () => import('./${code}/ui.js'),`).join('\n  ')}
}

export async function lazyLoadUi(code: string): Promise<Record<string, string>> {
  if (code === primaryLocale) return primaryUi
  return (await load[code]?.())?.ui ?? {}
}

type ContentLoader = () => Promise<Record<string, string>>
const legal: Partial<Record<string, Partial<Record<string, ContentLoader>>>> = {
${legal.join('\n')}
}

export async function loadLocaleContent(code: string, module: string): Promise<Record<string, string>> {
  return (await legal[code]?.[module]?.()) ?? {}
}
`
  await writeFile(file, await formatGeneratedSource(contents, file))
}

type LoadDictionary = (locale: string) => Promise<Record<string, string> | undefined>

/** Read the exact dictionaries the installed runtime loaders serve for these locales. */
export async function appBondLocaleKeys(
  locales: readonly string[],
  bonds: readonly string[],
  resolvePackage: (name: string) => Promise<string | null>,
): Promise<ReadonlyMap<string, ReadonlySet<string>>> {
  const dictionaries = await Promise.all(
    bonds.map(async (name) => {
      const root = await resolvePackage(name)
      if (!root) throw new Error(`Install ${name} before generating the app translation types.`)
      const manifest = JSON.parse(readFileSync(join(root, 'package.json'), 'utf-8')) as {
        exports?: { './loader.js'?: { import?: string } }
      }
      const entry = manifest.exports?.['./loader.js']?.import
      if (!entry) throw new Error(`${name} does not export its locale loader.`)
      // A source checkout found through the registry path has no build output until it is built.
      if (!existsSync(join(root, entry)))
        throw new Error(
          `${name} at ${root} has no ${entry.replace(/^\.\//, '')}: install the package (npm install) or build that copy, then run this again.`,
        )
      const { loadLocaleModule } = (await import(pathToFileURL(join(root, entry)).href)) as {
        loadLocaleModule: LoadDictionary
      }
      return loadLocaleModule
    }),
  )
  return new Map(
    await Promise.all(
      locales.map(async (locale) => {
        const keys = new Set<string>()
        for (const catalog of await Promise.all(dictionaries.map((load) => load(locale)))) {
          for (const [key, value] of Object.entries(catalog ?? {})) {
            if (typeof value === 'string') keys.add(key)
          }
        }
        return [locale, keys] as const
      }),
    ),
  )
}

/**
 * The entry of the i18n setup package that loads no locale bond itself (`<setup>/offered.js`), when
 * the copy the project installs has one. An app with managed locales then loads the common bond
 * with the others, in its locales/packages.ts; the default entry loads it through its own
 * `loader.js`, which lists all 79 languages.
 *
 * @param setupPackage - The package exporting `setupI18nDefault`.
 * @param from - A directory of the project.
 * @returns The entry's specifier, or undefined when the installed copy has none.
 */
export function offeredSetupEntry(setupPackage: string, from: string): string | undefined {
  const dir = installedPackageDir(setupPackage, from)
  if (!dir) return undefined
  const { exports } = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf-8')) as {
    exports?: Record<string, unknown>
  }
  return exports?.['./offered.js'] ? `${setupPackage}/offered.js` : undefined
}

/** The first line of each module {@link writeAppPackageLocales} writes. */
const PACKAGE_LOCALES_HEADER = '// Generated by mlcl from the installed locale bonds'

/**
 * Write the companion locale bonds' strings for the languages an app with managed locales offers:
 * `packages.<code>.ts` imports that language from each bond's own file for it, and `packages.ts`
 * maps each code to its module and exports the `loadPackageLocales` its i18n bond calls. Each
 * language is then one chunk of the build. Each bond's `loader.js` lists all 79 languages, so a
 * bundler builds all 79 for every bond: an English-only app with 15 bonds built 1,185 locale
 * chunks, and its dev server loaded 1.41 MB of dictionaries for 14 KB of English.
 *
 * A language a bond lacks falls back to its base language (`es-MX` → `es`), as the bond's own
 * loader does, and is left out when the bond has neither. A bond whose installed version does
 * not publish its languages one by one (`<package>/<code>.js`) is still loaded through its
 * `loader.js`; importing its root instead would load every language in dev and in `tsc`.
 *
 * @param dir - The app's locales directory (`appLocaleDirectory`).
 * @param locales - The languages the app offers, primary first.
 * @param bonds - The locale bonds its i18n bond loads, with the local name for each.
 * @param resolvePackage - Finds an installed package's directory.
 */
export async function writeAppPackageLocales(
  dir: string,
  locales: readonly string[],
  bonds: readonly { pkg: string; local: string }[],
  resolvePackage: (name: string) => Promise<string | null>,
): Promise<void> {
  const installed = await Promise.all(
    bonds.map(async ({ pkg, local }) => {
      const root = await resolvePackage(pkg)
      if (!root) throw new Error(`Install ${pkg} before generating the app's locale modules.`)
      const manifest = JSON.parse(readFileSync(join(root, 'package.json'), 'utf-8')) as {
        exports?: Record<string, { import?: string } | undefined>
      }
      const entry = manifest.exports?.['./loader.js']?.import
      if (!entry || !existsSync(join(root, entry)))
        throw new Error(
          `${pkg} at ${root} has no built locale loader: install the package (npm install) or build that copy, then run this again.`,
        )
      const { localeCodes } = (await import(pathToFileURL(join(root, entry)).href)) as {
        localeCodes?: readonly string[]
      }
      if (!localeCodes) throw new Error(`${pkg}'s locale loader does not list its languages.`)
      return {
        pkg,
        local,
        codes: new Set(localeCodes),
        perLanguage: Boolean(manifest.exports?.['./*.js']),
      }
    }),
  )
  const header = `${PACKAGE_LOCALES_HEADER} and package.json molecule.locales.
// \`${CLI_COMMAND} add <package> --inject\` and \`${CLI_COMMAND} locale add <code>\` rewrite it.`
  for (const code of locales) {
    const key = code.replace('_', '-')
    const base = key.split('-')[0]!
    const imported = installed
      .filter(({ perLanguage }) => perLanguage)
      .flatMap(({ pkg, local, codes }) => {
        const file = codes.has(key) ? key : codes.has(base) ? base : null
        return file
          ? [
              {
                local,
                line: `import { ${file.replace('-', '')} as ${local} } from '${pkg}/${file}.js'`,
              },
            ]
          : []
      })
    const file = join(dir, `packages.${code}.ts`)
    const contents = `${header}
${imported.map(({ line }) => line).join('\n')}

export const strings: Record<string, string> = { ${imported.map(({ local }) => `...${local}`).join(', ')} }
`
    await writeGenerated(
      file,
      await formatGeneratedSource(sortImportStatements(contents, file), file),
    )
  }
  for (const entry of await readdir(dir)) {
    const code = /^packages\.(.+)\.ts$/.exec(entry)?.[1]
    if (!code || locales.includes(code)) continue
    const stale = join(dir, entry)
    if (readFileSync(stale, 'utf-8').startsWith(PACKAGE_LOCALES_HEADER)) await rm(stale)
  }
  const whole = installed.filter(({ perLanguage }) => !perLanguage)
  const index = join(dir, 'packages.ts')
  const contents = `${header}
${whole.map(({ pkg, local }) => `import { loadLocaleModule as ${local} } from '${pkg}/loader.js'`).join('\n')}

// Each language is its own module, fetched when the app switches to it.
const load: Partial<Record<string, () => Promise<{ strings: Record<string, string> }>>> = {
  ${locales.map((code) => `${JSON.stringify(code)}: () => import('./packages.${code}.js'),`).join('\n  ')}
}
${
  whole.length > 0
    ? `
// These installed bonds do not publish their languages one by one, so each loads through its
// own loader, which lists all of them. An update of the bond, then \`${CLI_COMMAND} inject\`, moves it
// into the modules above.
const loaders = [${whole.map(({ local }) => local).join(', ')}]

/** The installed locale bonds' strings in one of the languages this app offers. */
export async function loadPackageLocales(code: string): Promise<Record<string, string> | undefined> {
  const [own, ...bonds] = await Promise.all([load[code]?.(), ...loaders.map((loader) => loader(code))])
  const strings: Record<string, string> = {}
  for (const each of [...bonds, own?.strings]) Object.assign(strings, each)
  return strings
}
`
    : `
/** The installed locale bonds' strings in one of the languages this app offers. */
export async function loadPackageLocales(code: string): Promise<Record<string, string> | undefined> {
  return (await load[code]?.())?.strings
}
`
}`
  await writeGenerated(
    index,
    await formatGeneratedSource(sortImportStatements(contents, index), index),
  )
}

/** Write a generated file only when its contents change, so a watcher does not rebuild for nothing. */
async function writeGenerated(file: string, contents: string): Promise<void> {
  if (!existsSync(file) || readFileSync(file, 'utf-8') !== contents) await writeFile(file, contents)
}

/** The compiler checks call sites as part of the app's existing build and editor typechecks. */
export async function writeAppLocaleTypes(
  dir: string,
  locales: readonly string[],
  bondKeys: ReadonlyMap<string, ReadonlySet<string>> = new Map(),
): Promise<void> {
  const i18n = requirePackageByRole('app', 'core', 'i18n')
  const primaryKeys = [...(bondKeys.get(locales[0]) ?? [])]
  const shared = new Set(
    primaryKeys.filter((key) => locales.every((l) => bondKeys.get(l)?.has(key))),
  )
  const catalogs = await Promise.all(
    locales.map(async (code) => {
      const modules = await readdir(join(dir, code))
      const app = ['ui', ...LEGAL_MODULES]
        .filter((name) => modules.includes(`${name}.ts`))
        .map((name) => ({ name, alias: `${code.replace('-', '')}_${name}` }))
      const extra = [...(bondKeys.get(code) ?? [])].filter((key) => !shared.has(key)).sort()
      return {
        imports: app.map(
          ({ name, alias }) => `import type { ${name} as ${alias} } from './${code}/${name}.js'`,
        ),
        member: `    ${JSON.stringify(code)}: ${[
          'SharedBondKeys',
          ...app.map(({ alias }) => `CatalogKeys<typeof ${alias}>`),
          ...extra.map((key) => JSON.stringify(key)),
        ].join(' | ')}`,
      }
    }),
  )
  const file = join(dir, 'catalogs.d.ts')
  const contents = `// Generated from the app catalogs and installed locale bonds by mlcl.
import '${i18n}'
${catalogs.flatMap(({ imports }) => imports).join('\n')}

type CatalogKeys<T> = string extends keyof T ? never : Extract<keyof T, string>
type SharedBondKeys = ${
    [...shared]
      .sort()
      .map((key) => JSON.stringify(key))
      .join(' | ') || 'never'
  }

declare module '${i18n}' {
  interface TranslationCatalogs {
${catalogs.map(({ member }) => member).join('\n')}
  }
}
`
  const next = await formatGeneratedSource(sortImportStatements(contents, file), file)
  if (!existsSync(file) || readFileSync(file, 'utf-8') !== next) await writeFile(file, next)
}
