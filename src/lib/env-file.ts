/**
 * Shared `.env` secret rendering and append logic.
 *
 * The ONE source of truth for how a registry secret renders into a project's
 * `.env` file (label/instructions/setupUrl/example comment block followed by
 * the `KEY=value` line). Two consumers:
 *
 * - `mlcl create` — `generateEnvFile()` in `scaffold.ts` writes the initial
 *   `.env` for a fresh project.
 * - `mlcl inject` (and `mlcl add --inject`) — `appendSecretsToEnvFile()`
 *   appends the newly-injected packages' secrets to an EXISTING project's
 *   `.env`, never touching lines that are already there.
 *
 * @module
 */

import { chmod, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

import type { MoleculeSecret } from './schema.js'
import { generateSecretValues } from './secret-generate.js'

/**
 * Matches a `.env` assignment line and captures its key. Also matches
 * commented-out assignments (`# KEY=...`) so a key a user deliberately
 * disabled is still treated as "present" and never re-appended. Guidance
 * comments (`# Get it here: ...`) never match — the text before `=` must be
 * a bare env identifier.
 */
const ENV_KEY_PATTERN = /^\s*#?\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=/

/**
 * Parse the set of env keys defined (or commented out) in `.env` content.
 *
 * @param content - Raw `.env` file content.
 * @returns Set of key names found in assignment lines.
 */
export function parseEnvKeys(content: string): Set<string> {
  const keys = new Set<string>()
  for (const line of content.split(/\r?\n/)) {
    const match = ENV_KEY_PATTERN.exec(line)
    if (match) keys.add(match[1])
  }
  return keys
}

/**
 * Filter secrets to the ones that belong in a given project type's `.env`:
 *
 * - `app` → ONLY `VITE_*` vars (Vite only embeds VITE_-prefixed env into the
 *   client bundle; anything else is noise that suggests "you might use this
 *   in the frontend" when you can't).
 * - `api` → everything EXCEPT `VITE_*` (frontend-only vars don't belong on
 *   the backend).
 *
 * Also deduplicates by name (first occurrence wins).
 *
 * @param secrets - Secrets aggregated from package metadata (registry).
 * @param projectType - 'api' or 'app'.
 * @param excludeKeys - Key names to always skip (e.g. baseline vars the
 *   caller already wrote, like PORT / NODE_ENV / VITE_API_URL).
 * @returns The applicable, deduplicated secrets in input order.
 */
export function filterEnvSecrets(
  secrets: MoleculeSecret[],
  projectType: 'api' | 'app',
  excludeKeys: Iterable<string> = [],
): MoleculeSecret[] {
  const seen = new Set(excludeKeys)
  return secrets.filter((secret) => {
    if (seen.has(secret.name)) return false
    const isViteVar = secret.name.startsWith('VITE_')
    if (projectType === 'app' && !isViteVar) return false
    if (projectType === 'api' && isViteVar) return false
    seen.add(secret.name)
    return true
  })
}

/**
 * Resolve the value written for `DATABASE_URL`, binding the db-name slot of
 * the connection string to the user's project instead of a generic
 * placeholder. Postgres treats unquoted hyphens as subtraction, so the db
 * slot can't contain them: `my-blog-test` → `my_blog_test`.
 *
 * @param value - The registry default (or empty string when none).
 * @param projectName - The project's name (may contain hyphens).
 * @returns The connection string with a db-safe database name.
 */
export function resolveDatabaseUrlValue(value: string, projectName: string): string {
  const dbSafeName = projectName.replace(/-/g, '_')
  if (/\bmyapp\b/.test(value)) {
    return value.replace(/\bmyapp\b/, dbSafeName)
  }
  if (!value || value === 'postgres://localhost:5432/') {
    // No registry default — emit a sensible local-Docker default.
    return `postgres://molecule:molecule@127.0.0.1:5432/${dbSafeName}`
  }
  return value.replace(new RegExp(`/${projectName}$`), `/${dbSafeName}`)
}

/**
 * Options for {@link renderEnvSecretLines}.
 */
export interface RenderEnvSecretOptions {
  /** True when the value was auto-generated from the secret's `generate` kind. */
  generated: boolean
  /**
   * The command that generated the value — rendered into the
   * "Auto-generated by …" comment (e.g. 'mlcl create', 'mlcl inject').
   */
  generatedBy: string
}

/**
 * Render one secret as `.env` lines: setup-guidance comments (from the
 * registry's label / instructions / setupUrl / example enrichment) followed
 * by the `KEY=value` assignment. This is the canonical per-secret format —
 * both scaffold and inject write exactly this block.
 *
 * @param secret - The registry secret to render.
 * @param value - The value to assign (may be empty when the user must fill it in).
 * @param options - Generation context (auto-generated marker + attribution).
 * @returns The lines for this secret, without a trailing blank line.
 */
export function renderEnvSecretLines(
  secret: MoleculeSecret,
  value: string,
  options: RenderEnvSecretOptions,
): string[] {
  const lines: string[] = []

  // Setup guidance from the registry (label / instructions / setupUrl /
  // example) renders as comments so the .env itself tells the user what
  // each credential is and where to get it.
  const title = secret.label
    ? `${secret.label}${secret.required === false ? ' (optional)' : ''}`
    : ''
  if (title || secret.instructions) {
    lines.push(`# ${[title, secret.instructions].filter(Boolean).join(' — ')}`)
  }
  if (options.generated) {
    lines.push(`# Auto-generated by ${options.generatedBy} — no setup needed.`)
  } else {
    if (secret.setupUrl) lines.push(`# Get it here: ${secret.setupUrl}`)
    if (secret.example && !value) lines.push(`# Example: ${secret.example}`)
  }
  lines.push(`${secret.name}=${value}`)

  return lines
}

/**
 * One secret appended to `.env` by {@link appendSecretsToEnvFile}.
 */
export interface AppendedEnvSecret {
  /** The env key that was appended. */
  name: string
  /** True when a real value was auto-generated (no manual setup needed). */
  generated: boolean
}

/**
 * Options for {@link appendSecretsToEnvFile}.
 */
export interface AppendSecretsOptions {
  /**
   * The command attributed in the generated comments and the created-file
   * header (e.g. 'mlcl inject', 'mlcl swap'). Defaults to 'mlcl inject'.
   */
  generatedBy?: string
  /**
   * Compute the result without touching the filesystem — used by dry-run /
   * preview flows to show exactly what a real run would append.
   */
  dryRun?: boolean
}

/**
 * Result of {@link appendSecretsToEnvFile}.
 */
export interface EnvAppendResult {
  /** Absolute path of the `.env` file that was inspected/written. */
  envPath: string
  /** True when the `.env` file did not exist and was created fresh. */
  created: boolean
  /** Secrets appended (in order), with generation status. */
  appended: AppendedEnvSecret[]
  /** Applicable secret keys that were already present and left untouched. */
  skipped: string[]
}

/**
 * Append newly-required secrets to an existing project's `.env`.
 *
 * - Filters the secrets to the project type (see {@link filterEnvSecrets}).
 * - Parses the keys already present and NEVER overwrites or duplicates an
 *   existing line — the existing content is preserved byte-for-byte.
 * - Appends each missing secret in the same commented format `mlcl create`
 *   scaffolds ({@link renderEnvSecretLines}), auto-generating values for
 *   `generate`-marked secrets so they need no manual setup.
 * - Creates `.env` with a header comment when the file doesn't exist.
 * - Idempotent: a re-run appends nothing new.
 *
 * @param projectPath - The project workspace directory containing `.env`.
 * @param secrets - Secrets aggregated from the injected packages (registry).
 * @param projectType - 'api' or 'app' — drives the VITE_ filter.
 * @param projectName - Optional project name used to bind the DATABASE_URL
 *   db-name slot when that secret is appended.
 * @param options - Attribution + dry-run behavior (see {@link AppendSecretsOptions}).
 * @returns What was appended, skipped, and whether the file was created.
 */
export async function appendSecretsToEnvFile(
  projectPath: string,
  secrets: MoleculeSecret[],
  projectType: 'api' | 'app',
  projectName = 'my-app',
  options: AppendSecretsOptions = {},
): Promise<EnvAppendResult> {
  const generatedBy = options.generatedBy ?? 'mlcl inject'
  const envPath = join(projectPath, '.env')

  let existing: string | null = null
  try {
    existing = await readFile(envPath, 'utf-8')
  } catch (_error) {
    // .env doesn't exist yet — we'll create it with a header below.
  }

  const applicable = filterEnvSecrets(secrets, projectType)
  const existingKeys = existing === null ? new Set<string>() : parseEnvKeys(existing)
  const missing = applicable.filter((secret) => !existingKeys.has(secret.name))
  const skipped = applicable
    .filter((secret) => existingKeys.has(secret.name))
    .map((secret) => secret.name)

  if (missing.length === 0) {
    return { envPath, created: false, appended: [], skipped }
  }

  // Secrets marked `generate` in the registry (JWT keypair, VAPID keypair,
  // random keys) never require user setup — generate real values now.
  // (Pure in-memory generation, so it's safe in dry-run too — the values are
  // simply discarded; only the generated/not-generated status is reported.)
  const generated = generateSecretValues(missing)

  if (options.dryRun) {
    return {
      envPath,
      created: existing === null,
      appended: missing.map((secret) => ({
        name: secret.name,
        generated: generated.has(secret.name),
      })),
      skipped,
    }
  }

  const blocks: string[] = []
  for (const secret of missing) {
    let value = generated.get(secret.name) ?? secret.default ?? ''
    if (secret.name === 'DATABASE_URL') {
      value = resolveDatabaseUrlValue(value, projectName)
    }
    blocks.push(
      renderEnvSecretLines(secret, value, {
        generated: generated.has(secret.name),
        generatedBy,
      }).join('\n'),
    )
  }

  let output: string
  if (existing === null) {
    output = [
      '# Environment variables',
      `# Generated by ${generatedBy}`,
      '',
      blocks.join('\n\n'),
    ].join('\n')
  } else {
    // Preserve existing content byte-for-byte; just ensure exactly one
    // blank line separates it from the appended blocks.
    let head = existing
    if (head.length > 0 && !head.endsWith('\n')) head += '\n'
    const separator = head.length === 0 || head.endsWith('\n\n') ? '' : '\n'
    output = head + separator + blocks.join('\n\n')
  }
  // The .env can carry generated secrets (JWT private key PEM, VAPID keypair,
  // hex API keys) — write it owner-only. `mode` only applies when the file is
  // CREATED, so also chmod: the append path must not leave secrets in a
  // world-readable .env a user or earlier tool created with default umask.
  await writeFile(envPath, output.replace(/\n*$/, '\n'), { mode: 0o600 })
  await chmod(envPath, 0o600)

  return {
    envPath,
    created: existing === null,
    appended: missing.map((secret) => ({
      name: secret.name,
      generated: generated.has(secret.name),
    })),
    skipped,
  }
}
