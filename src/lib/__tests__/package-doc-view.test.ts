/**
 * The bounded README view `mlcl docs` and the MCP `read_package_doc` tool print. A generated
 * `@molecule/*` README can pass 90 KB; printed whole, most of it fills an agent's context to find
 * one function. A short README still comes back whole.
 */
import { describe, expect, it } from 'vitest'

import { DOC_VIEW_MAX_CHARS, docHeadings, packageDocView } from '../package-doc-view.js'

const HINT = 'npx mlcl docs @molecule/api-demo --section "<heading>"'

/** A generated-shape README: a header comment, an overview, and an API reference of `size`. */
function readme(size: number): string {
  const filler = 'x'.repeat(200)
  const functions = ['findById', 'findOne', 'findMany']
    .map((name) => `#### \`${name}(table, options)\`\n\nFinds rows for ${name}.\n\n${filler}\n`)
    .join('\n')
  let body = [
    '<!--\nAUTO-GENERATED — DO NOT EDIT THIS FILE.\n-->',
    '',
    '# @molecule/api-demo',
    '',
    'The demo package overview.',
    '',
    '## Quick Start',
    '',
    '```ts',
    '# not a heading: a comment inside a fence',
    '```',
    '',
    '## API',
    '',
    '### Functions',
    '',
    functions,
    '### Types',
    '',
    '#### `DemoRow`',
    '',
    'A demo row.',
    '',
    '## Injection Notes',
    '',
  ].join('\n')
  while (body.length < size) body += `${filler}\n`
  return body
}

describe('packageDocView', () => {
  it('returns a short README whole, without the generator comment', () => {
    const doc = readme(1_000)
    const { text, found } = packageDocView(doc, { sectionHint: HINT })
    expect(found).toBe(true)
    expect(text.startsWith('# @molecule/api-demo')).toBe(true)
    expect(text).toContain('## Injection Notes')
    expect(text).not.toContain('AUTO-GENERATED')
  })

  it('prints a long README as its overview and an index of its sections and exported names', () => {
    const doc = readme(DOC_VIEW_MAX_CHARS * 3)
    const { text } = packageDocView(doc, { sectionHint: HINT })
    expect(text.length).toBeLessThan(DOC_VIEW_MAX_CHARS)
    expect(text).toContain('The demo package overview.')
    expect(text).toContain(HINT)
    expect(text).toContain('- Quick Start')
    expect(text).toContain('  - Functions\n    findById, findOne, findMany')
    expect(text).toContain('  - Types\n    DemoRow')
    expect(text).not.toContain('Finds rows for findMany')
  })

  it('reads an exported function by the name the index lists, up to the next heading of its level', () => {
    const { text, found } = packageDocView(readme(DOC_VIEW_MAX_CHARS * 3), {
      section: 'findMany',
      sectionHint: HINT,
    })
    expect(found).toBe(true)
    expect(text.startsWith('#### `findMany(table, options)`')).toBe(true)
    expect(text).toContain('Finds rows for findMany.')
    expect(text).not.toContain('### Types')
  })

  it('reads a whole heading, its subsections included', () => {
    const { text } = packageDocView(readme(1_000), { section: 'functions', sectionHint: HINT })
    expect(text).toContain('Finds rows for findById.')
    expect(text).toContain('Finds rows for findMany.')
    expect(text).not.toContain('DemoRow')
  })

  it('answers a missing section with the index, and says it was not found', () => {
    const { text, found } = packageDocView(readme(1_000), {
      section: 'deleteAll',
      sectionHint: HINT,
    })
    expect(found).toBe(false)
    expect(text).toContain('No section "deleteAll"')
    expect(text).toContain('findById, findOne, findMany')
  })

  it('cuts a section longer than the bound and says how to narrow it', () => {
    const doc = `# pkg\n\n## API\n\n${'y'.repeat(DOC_VIEW_MAX_CHARS * 2)}\n`
    const { text } = packageDocView(doc, { section: 'API', sectionHint: HINT })
    expect(text.length).toBeLessThan(DOC_VIEW_MAX_CHARS + 200)
    expect(text).toContain(`ask for a narrower section: ${HINT}`)
  })
})

describe('docHeadings', () => {
  it('skips lines inside code fences', () => {
    const titles = docHeadings(readme(1_000)).map((heading) => heading.title)
    expect(titles).not.toContain('not a heading: a comment inside a fence')
    expect(titles).toContain('Quick Start')
  })
})
