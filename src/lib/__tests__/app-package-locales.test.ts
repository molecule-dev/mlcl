/**
 * `writeAppPackageLocales` writes, for an app with managed locales, one module per offered language
 * that imports that language from each locale bond's own file. Through each bond's `loader.js`,
 * which lists all 79 languages, a bundler built a chunk for every language of every bond: an
 * English-only app with 15 bonds built 1,185 of them (harness smoke run 4, 2026-11-28).
 *
 * @module
 */
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { afterEach, describe, expect, it } from 'vitest'

import { writeAppPackageLocales } from '../app-locales.js'

let root: string | null = null
afterEach(() => {
  if (root) rmSync(root, { recursive: true, force: true })
  root = null
})

/**
 * An installed locale bond: its manifest and a built loader that lists its languages.
 *
 * @param dir - Where to write it.
 * @param codes - The languages it carries.
 * @param perLanguage - Whether its exports publish each language at `./<code>.js`.
 * @returns Its directory.
 */
function bond(dir: string, codes: string[], perLanguage: boolean): string {
  mkdirSync(join(dir, 'dist'), { recursive: true })
  const exports: Record<string, unknown> = {
    '.': { types: './dist/index.d.ts', import: './dist/index.js' },
    './loader.js': { types: './dist/loader.d.ts', import: './dist/loader.js' },
  }
  if (perLanguage) exports['./*.js'] = { types: './dist/*.d.ts', import: './dist/*.js' }
  writeFileSync(join(dir, 'package.json'), JSON.stringify({ type: 'module', exports }))
  writeFileSync(
    join(dir, 'dist', 'loader.js'),
    `export const localeCodes = ${JSON.stringify(codes)}\n`,
  )
  return dir
}

describe('writeAppPackageLocales', () => {
  it("imports each offered language from each bond's file for it", async () => {
    root = mkdtempSync(join(tmpdir(), 'mlcl-package-locales-'))
    const dirs = {
      '@molecule/app-locales-auth': bond(join(root, 'auth'), ['en', 'es', 'zh-TW'], true),
      '@molecule/app-locales-ui': bond(join(root, 'ui'), ['en', 'es', 'ja', 'zh-TW'], true),
      '@molecule/app-locales-old': bond(join(root, 'old'), ['en', 'es', 'ja'], false),
    }
    const locales = join(root, 'app', 'src', 'locales')
    mkdirSync(locales, { recursive: true })
    // A module for a language the app no longer offers, and a file of the app's own.
    writeFileSync(
      join(locales, 'packages.de.ts'),
      '// Generated by mlcl from the installed locale bonds and package.json molecule.locales.\n',
    )
    writeFileSync(join(locales, 'packages.notes.ts'), '// mine\n')

    await writeAppPackageLocales(
      locales,
      ['en', 'es-MX', 'ja', 'zh-TW'],
      [
        { pkg: '@molecule/app-locales-auth', local: 'authLocales' },
        { pkg: '@molecule/app-locales-old', local: 'oldLocales' },
        { pkg: '@molecule/app-locales-ui', local: 'uiLocales' },
      ],
      async (name) => dirs[name as keyof typeof dirs] ?? null,
    )

    const read = (file: string): string => readFileSync(join(locales, file), 'utf-8')
    // A regional code a bond lacks takes its base language, as the bond's own loader does.
    expect(read('packages.es-MX.ts')).toContain(
      "import { es as authLocales } from '@molecule/app-locales-auth/es.js'",
    )
    expect(read('packages.zh-TW.ts')).toContain(
      "import { zhTW as uiLocales } from '@molecule/app-locales-ui/zh-TW.js'",
    )
    // A bond without the language is left out of that module.
    expect(read('packages.ja.ts')).not.toContain('app-locales-auth')
    expect(read('packages.ja.ts')).toContain('...uiLocales')
    // A bond whose installed version has no per-language files keeps its own loader.
    for (const code of ['en', 'es-MX', 'ja', 'zh-TW'])
      expect(read(`packages.${code}.ts`)).not.toContain('app-locales-old')
    expect(read('packages.ts')).toContain(
      "import { loadLocaleModule as oldLocales } from '@molecule/app-locales-old/loader.js'",
    )
    expect(read('packages.ts')).toContain("'es-MX': () => import('./packages.es-MX.js'),")
    // The module of a language no longer offered goes; a file mlcl did not write stays.
    expect(existsSync(join(locales, 'packages.de.ts'))).toBe(false)
    expect(read('packages.notes.ts')).toBe('// mine\n')
  })

  it('writes an empty module when no bond carries the language', async () => {
    root = mkdtempSync(join(tmpdir(), 'mlcl-package-locales-'))
    const auth = bond(join(root, 'auth'), ['en'], true)
    const locales = join(root, 'locales')
    mkdirSync(locales)
    await writeAppPackageLocales(
      locales,
      ['en', 'fr'],
      [{ pkg: '@molecule/app-locales-auth', local: 'authLocales' }],
      async () => auth,
    )
    expect(readFileSync(join(locales, 'packages.fr.ts'), 'utf-8')).toContain(
      'export const strings: Record<string, string> = {}',
    )
    expect(readFileSync(join(locales, 'packages.ts'), 'utf-8')).toContain(
      'return (await load[code]?.())?.strings',
    )
  })
})
