import { readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'

import ts from 'typescript'
import { expect, it } from 'vitest'

const ROOT = join(import.meta.dirname, '../../..')
const SCOPES = ['src', 'mcp/src']
const commands = [
  ...readdirSync(join(ROOT, 'src/commands'))
    .filter((name) => !name.startsWith('_'))
    .map((name) => name.replace(/\.ts$/, '')),
  'help',
  'login',
  'logout',
  'whoami',
  '--help',
  '--version',
  '<command>',
]
const hardcodedCommand = new RegExp(
  `(?<![\\w./@-])(?:npx (?:--yes |-y )?)?mlcl[ \\t]+(?:${commands.join('|')})(?![\\w-])|\\bnpx mlcl@`,
)

// Existing file-format markers and a command executed by an unattended agent hook.
const nonInstructions: Record<string, RegExp> = {
  'src/lib/docs-generator.ts': /^<!--\nAUTO-GENERATED.*\nGenerated by `mlcl sync-docs` from /,
  'src/lib/env-file.ts': /^mlcl inject$/,
  'src/lib/extend-api-wiring.ts': /^\/\/ Generated by mlcl create from the packages you selected/,
  'src/lib/injector.ts': /^\/\/ Generated by mlcl create from the packages you selected/,
  'src/lib/scaffold.ts': /^# Generated by mlcl create$/,
  'src/lib/setup-sql.ts': /^-- mlcl setup SQL of /,
  'src/lib/stop-hooks.ts': /^npx --yes mlcl check --stop-hook$/,
}

it('uses the shared CLI prefix for runnable commands in source strings', () => {
  const violations: string[] = []
  for (const scope of SCOPES) {
    for (const entry of readdirSync(join(ROOT, scope), { recursive: true, encoding: 'utf8' })) {
      if (!entry.endsWith('.ts') || entry.split(/[\\/]/).includes('__tests__')) continue
      const path = join(scope, entry)
      const source = ts.createSourceFile(
        path,
        readFileSync(join(ROOT, path), 'utf8'),
        ts.ScriptTarget.Latest,
        true,
      )
      function visit(node: ts.Node): void {
        const dynamic = ts.isTemplateHead(node) || ts.isTemplateMiddle(node)
        if (ts.isStringLiteralLike(node) || ts.isTemplateLiteralToken(node)) {
          if (
            (hardcodedCommand.test(node.text) || (dynamic && /\bmlcl $/.test(node.text))) &&
            !nonInstructions[path.replaceAll('\\', '/')]?.test(node.text) &&
            !(
              ts.isPropertyAssignment(node.parent) &&
              node.parent.name.getText(source) === 'generatedBy'
            )
          ) {
            const { line } = source.getLineAndCharacterOfPosition(node.getStart(source))
            violations.push(`${path}:${line + 1}`)
          }
        }
        ts.forEachChild(node, visit)
      }
      visit(source)
    }
  }
  expect(violations).toEqual([])
})
