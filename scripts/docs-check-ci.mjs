#!/usr/bin/env node
/**
 * Run the fleet-wide README.md drift check only when it can find anything.
 *
 * `mlcl sync-docs --check` runs ts-morph over ~919 packages and takes minutes.
 * Almost every commit cannot possibly change a generated doc, so paying that on
 * every CI run is waste — the check is only meaningful when a GENERATOR input
 * moved, because those are the changes that alter output for packages nobody
 * touched.
 *
 * Per-package source changes need no sweep: molecule's pre-commit hook already
 * regenerates the staged package's README (and its cross-doc dependents) via
 * regen-molecule-docs.mjs, in the same commit. This gate exists for the other
 * class — a change to the generator or to registry.json that silently invalidates
 * docs across the fleet with nothing staged to trigger regeneration.
 *
 * So: if any generator input changed, run the full check. Otherwise skip and say
 * so. A skip is reported, never silent — a gate whose "pass" and "did not run"
 * look alike is how four gates in this workspace sat green for months.
 *
 *   node scripts/docs-check-ci.mjs                # base: origin/main
 *   node scripts/docs-check-ci.mjs --base=<ref>
 *   node scripts/docs-check-ci.mjs --force        # always run the full check
 */
import { execFileSync, spawnSync } from 'node:child_process'
import console from 'node:console'
import { dirname, join } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const args = process.argv.slice(2)
const FORCE = args.includes('--force')
const BASE = (args.find((a) => a.startsWith('--base=')) || '').split('=')[1]

/**
 * Files whose contents decide what EVERY generated README.md looks like.
 *
 * Deliberately over-broad: a false "run the check" costs minutes of CI, a false
 * "skip" ships drift. When in doubt, add the path here.
 */
const GENERATOR_INPUTS = [
  'registry.json',
  'src/lib/docs-generator.ts',
  'src/lib/docs-sync.ts',
  'src/lib/api-extractor.ts',
  'src/lib/format.ts',
  'src/lib/features.ts',
  'src/commands/sync-docs.ts',
  'scripts/regen-molecule-docs.mjs',
  'scripts/docs-check-ci.mjs',
]

/**
 * Lists files changed against a base ref.
 *
 * @param base - Ref to diff against.
 * @returns Changed paths, or null when the ref is unavailable.
 */
const changedSince = (base) => {
  const result = spawnSync('git', ['diff', '--name-only', `${base}...HEAD`], {
    cwd: ROOT,
    encoding: 'utf8',
  })
  if (result.status !== 0) return null
  return result.stdout.split('\n').filter(Boolean)
}

const base = BASE || process.env.GITHUB_BASE_REF || 'origin/main'
const changed = FORCE ? null : changedSince(base)

if (!FORCE) {
  if (changed === null) {
    // Could not diff — a shallow clone, a missing ref, a detached first commit.
    // Run the full check rather than skip: "I could not look" must never be
    // reported as "I looked and it is fine".
    console.log(`Cannot diff against "${base}" — running the full check.`)
  } else {
    const hits = changed.filter((file) => GENERATOR_INPUTS.includes(file))
    if (!hits.length) {
      console.log(
        `Skipped: no doc-generator input changed vs ${base}.\n` +
          `  (${changed.length} file(s) changed; per-package docs are regenerated by\n` +
          `   molecule's pre-commit hook, so only generator/registry changes need a sweep.)`,
      )
      process.exit(0)
    }
    console.log(`Generator input(s) changed — running the full check:\n  ${hits.join('\n  ')}`)
  }
}

try {
  execFileSync('node', ['bin/run.js', 'sync-docs', '--check'], { cwd: ROOT, stdio: 'inherit' })
} catch (_error) {
  // Intentionally ignored: sync-docs has already printed which files differ and
  // how to regenerate them, so rethrowing would only stack a second, vaguer
  // message on top of the actionable one.
  process.exit(1)
}
